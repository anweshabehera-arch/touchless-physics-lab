/**
 * Returns practical guidance on how to record empirical data for each experiment.
 * @param {string} expId
 * @returns {string}
 */
export function getHowToMeasureGuide(expId) {
  switch (expId) {
    case 'newton':
      return "Launch the Force Arena in the 3D lab and exert an unbalanced push force vector on the rescue cart using your hand or keyboard thrusters [D / →].";
    case 'impulse':
      return "Trigger the pneumatic piston or thrust with your hand into the impact chamber to record force over contact time and impart momentum.";
    case 'hooke':
      return "Grab or pull the suspended spring mass away from the central equilibrium position (x = 0) and release it to initiate harmonic oscillation.";
    case 'collision':
      return "Launch Striker Pod 1 toward Target Drone 2 with the desired collision restitution mode (Elastic or Inelastic) to record momentum transfer.";
    case 'projectile':
      return "Adjust the cannon elevation angle and launch speed, then fire the projectile to trace and measure a parabolic trajectory.";
    case 'pendulum':
      return "Displace the pendulum bob from its vertical datum to set an initial release angle (θ₀) and observe period and energy conservation.";
    case 'electric':
      return "Move the mobile test charge probe through the 2D electrostatic grid to sample electric field vectors and electric potential.";
    case 'wave':
      return "Adjust the phase shift slider (Δφ) or frequency controls to produce constructive reinforcement or destructive cancellation.";
    case 'optics':
      return "Direct the incident light beam across the boundary interface to measure reflection, refraction angles, and Total Internal Reflection.";
    case 'incline':
      return "Increase the inclined plane slope angle (θ) past the critical angle of repose to observe static friction breakaway and sliding acceleration.";
    default:
      return "Interact with the virtual simulation in the laboratory to record real empirical physics telemetry.";
  }
}

/**
 * Returns a scientifically sound hypothesis for each experiment module.
 */
export function getExperimentHypothesis(expId, expDef) {
  if (expDef?.hypothesis) return expDef.hypothesis;
  switch (expId) {
    case 'newton':
      return "If an unbalanced net force is exerted on a mass, its acceleration will scale in direct linear proportion to force (a ∝ F_net) and inversely with mass.";
    case 'impulse':
      return "The mechanical impulse delivered by a force over contact time Δt (J = ∫F dt) will equal the total change in linear momentum (Δp).";
    case 'hooke':
      return "Restoring force generated by an elastic spring is directly proportional to displacement from equilibrium (F = -k·x), conserving mechanical energy.";
    case 'collision':
      return "In a closed physical system with negligible friction, total linear momentum is strictly conserved across elastic and inelastic collisions.";
    case 'projectile':
      return "Horizontal motion with zero acceleration and vertical motion under constant gravitational acceleration operate independently.";
    case 'pendulum':
      return "For small oscillation amplitudes, the period of a simple pendulum depends solely on cord length and gravitational field, independent of mass.";
    case 'electric':
      return "Electrostatic force follows Coulomb's inverse-square law, and multiple source charges superpose vectorially at any field point.";
    case 'wave':
      return "Overlapping harmonic waves superpose linearly, producing constructive reinforcement when in phase and destructive cancellation when in phase opposition.";
    case 'optics':
      return "The ratio of sines of incidence and refraction angles equals the ratio of refractive indices (Snell's Law), undergoing Total Internal Reflection beyond critical angle.";
    case 'incline':
      return "A block on an inclined ramp remains in static equilibrium until the tangent of the slope angle exceeds the static friction coefficient (tan θ > μ_s).";
    default:
      return `Physical measurements will conform to the theoretical predictions of ${expDef?.primaryFormula || 'governing laws'}.`;
  }
}

/**
 * Creates an immutable, experiment-specific lab report snapshot.
 *
 * @param {Object} options
 * @param {string} options.experimentId - Identifier of the experiment (e.g. 'newton', 'hooke')
 * @param {Object} [options.experiment] - Optional experiment definition object from EXPERIMENT_LIST
 * @param {Object} [options.physicsData] - Live or captured instantaneous physics state
 * @param {Object} [options.sessionMetrics] - Accumulated session telemetry (peaks, event flags)
 * @param {Object} [options.quizResult] - Quiz completion data ({ score, totalQuestions, passed })
 * @param {string} [options.studentName] - Name of the investigator
 * @param {Object} [options.userConfig] - User-configured settings (mass, angles, etc.)
 * @param {boolean} [options.hasMeasurements] - Explicit override for empirical measurement presence
 * @returns {Object} Structured immutable report snapshot
 */
export function createExperimentReportSnapshot({
  experimentId = 'newton',
  experiment: expParam = null,
  physicsData = {},
  sessionMetrics = null,
  quizResult = null,
  studentName = 'Student Physicist',
  userConfig = {},
  hasMeasurements: explicitHasMeasurements = undefined
} = {}) {
  const expDef =
    expParam ||
    EXPERIMENTS[experimentId] ||
    EXPERIMENT_LIST.find((e) => e.id === experimentId) ||
    EXPERIMENTS.newton;

  const id = expDef.id;
  const metrics = sessionMetrics || {};
  const phys = physicsData || {};

  // Timestamp
  const now = new Date();
  const timestamp = now.toLocaleString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  // Evaluate quiz mastery
  const rawScore =
    quizResult && typeof quizResult.score === 'number'
      ? Math.round(quizResult.score)
      : null;
  const isMastered = rawScore !== null && rawScore >= 70;

  let apparatus;
  let measurements = [];
  let analysis = {
    governingEquation: expDef.primaryFormula,
    isEmpiricallyVerified: false,
    verificationStatus: "AWAITING_DATA",
    verificationSummary: "Awaiting empirical telemetry.",
    theoreticalComparison: "",
    quantitativeComparison: null
  };

  let hasEmpiricalData;

  switch (id) {
    // ========================================================================
    // 1. NEWTON'S 2ND LAW
    // ========================================================================
    case 'newton': {
      const mass = Number(metrics.mass ?? phys.mass ?? userConfig.mass ?? 1.0);
      const dragCoeff = 0.55;
      const peakForce = Number(metrics.peakForce ?? (phys.force && phys.force > 0 ? phys.force : 0));
      const peakAccel = Number(metrics.peakAcceleration ?? (phys.acceleration && phys.acceleration > 0 ? phys.acceleration : 0));
      const peakVel = Number(metrics.peakVelocity ?? (phys.velocity && phys.velocity > 0 ? phys.velocity : 0));
      const peakP = Number(metrics.peakMomentum ?? (mass * peakVel));
      const peakKE = Number(metrics.peakKineticEnergy ?? (0.5 * mass * peakVel * peakVel));
      const dockAchieved = Boolean(metrics.dockAchieved || phys.inRescueZone);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || peakForce > 0.1 || peakVel > 0.05 || dockAchieved)
      );

      apparatus = [
        { parameter: "Object Mass (m)", value: mass.toFixed(2), unit: "Kilograms (kg)", notes: "Payload Cart Inertial Mass" },
        { parameter: "Viscous Damping Drag (b)", value: dragCoeff.toFixed(2), unit: "N·s/m", notes: "Track friction resistance" },
        { parameter: "Target Dock Zone", value: "0.46 – 0.70", unit: "Meters (m)", notes: "Precision landing bay" },
        { parameter: "Interaction Perimeter (R)", value: "0.55", unit: "Meters (m)", notes: "Proximity force interaction field" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Peak Applied Force (F_net)", value: peakForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Measured Acceleration (a_max)", value: peakAccel.toFixed(2), unit: "m/s²", isMeasured: true },
          { label: "Peak Linear Speed (v_max)", value: peakVel.toFixed(2), unit: "m/s", isMeasured: true },
          { label: "Linear Momentum (p_max)", value: peakP.toFixed(2), unit: "kg·m/s", isMeasured: true },
          { label: "Maximum Kinetic Energy", value: peakKE.toFixed(2), unit: "J", isMeasured: true },
          { label: "Rescue Target Status", value: dockAchieved ? "Safely Docked" : "In Transit", unit: "", isMeasured: true }
        ];

        const theoAccel = computeNewtonAcceleration(peakForce, mass);
        const diffAccel = Math.abs(peakAccel - theoAccel);
        const pctDev = theoAccel > 0 ? ((diffAccel / theoAccel) * 100).toFixed(1) : "0.0";

        analysis = {
          governingEquation: "F_{net} = m · a \\iff a = \\frac{F_{net}}{m}",
          isEmpiricallyVerified: peakForce > 0.1,
          verificationStatus: peakForce > 0.1 ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: peakForce > 0.1
            ? `Direct verification of Newton's 2nd Law. An applied net force of ${peakForce.toFixed(2)} N produced a peak acceleration of ${peakAccel.toFixed(2)} m/s² on mass m = ${mass.toFixed(2)} kg.`
            : "Cart motion observed, but peak force was below the minimum 0.1 N threshold for conclusive verification.",
          theoreticalComparison: `Theoretical undamped acceleration for F = ${peakForce.toFixed(2)} N and m = ${mass.toFixed(2)} kg is a_theo = ${theoAccel.toFixed(2)} m/s². The observed peak acceleration was ${peakAccel.toFixed(2)} m/s². Minor variations reflect simulation viscous damping (F_drag = -b·v).`,
          quantitativeComparison: [
            { metric: "Peak Acceleration", theoretical: `${theoAccel.toFixed(2)} m/s²`, observed: `${peakAccel.toFixed(2)} m/s²`, deviation: `${pctDev}%` },
            { metric: "Inertial Ratio (F / m)", theoretical: `${(peakForce / mass).toFixed(2)} m/s²`, observed: `${peakAccel.toFixed(2)} m/s²`, deviation: `${pctDev}%` }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 2. IMPULSE & MOMENTUM
    // ========================================================================
    case 'impulse': {
      const mass = Number(metrics.mass ?? phys.mass ?? 1.0);
      const peakForce = Number(metrics.peakForce ?? phys.peakForce ?? phys.force ?? 0);
      const contactTime = Number(metrics.contactTime ?? phys.contactTime ?? 0);
      const impulseJ = Number(metrics.impulseJ ?? phys.impulseJ ?? 0);
      const deltaP = Number(metrics.deltaMomentum ?? metrics.deltaP ?? phys.deltaMomentum ?? 0);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || peakForce > 0.1 || impulseJ > 0 || deltaP > 0)
      );

      apparatus = [
        { parameter: "Target Mass (m)", value: mass.toFixed(2), unit: "Kilograms (kg)", notes: "Target impact probe" },
        { parameter: "Nominal Strike Force", value: "25.00", unit: "Newtons (N)", notes: "Piston strike capability" },
        { parameter: "Piston Impact Perimeter", value: "0.38", unit: "Meters (m)", notes: "Contact impact boundary" }
      ];

      if (hasEmpiricalData) {
        const impartedVel = mass > 0 ? (deltaP / mass).toFixed(2) : "0.00";
        measurements = [
          { label: "Peak Contact Force (F_max)", value: peakForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Contact Duration (Δt)", value: (contactTime * 1000).toFixed(0), unit: "ms", isMeasured: true },
          { label: "Total Impulse (J = ∫F dt)", value: impulseJ.toFixed(3), unit: "N·s", isMeasured: true },
          { label: "Momentum Change (Δp)", value: deltaP.toFixed(3), unit: "kg·m/s", isMeasured: true },
          { label: "Imparted Velocity (Δv)", value: impartedVel, unit: "m/s", isMeasured: true }
        ];

        const impulseDiff = Math.abs(impulseJ - deltaP);
        const impulseTolerance = 0.1;
        const verified = verifyImpulseMomentumTheorem(impulseJ, deltaP, impulseTolerance);

        analysis = {
          governingEquation: "J = \\int F \\, dt = \\Delta p = m(v_f - v_i)",
          isEmpiricallyVerified: verified && (impulseJ > 0 || deltaP > 0),
          verificationStatus: verified ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: verified
            ? `Verified the Impulse-Momentum Theorem (J = Δp). Total impulse delivered (${impulseJ.toFixed(3)} N·s) matched momentum change (${deltaP.toFixed(3)} kg·m/s) within 0.05% numerical error.`
            : "Impulse and momentum change exhibited numerical deviation greater than allowable tolerance.",
          theoreticalComparison: `The time integral of the piston contact force J = ${impulseJ.toFixed(3)} N·s imparted a linear momentum change Δp = ${deltaP.toFixed(3)} kg·m/s to the ${mass.toFixed(2)} kg probe.`,
          quantitativeComparison: [
            { metric: "Impulse (J)", theoretical: `${deltaP.toFixed(3)} N·s`, observed: `${impulseJ.toFixed(3)} N·s`, deviation: `${(impulseDiff * 100).toFixed(2)}%` }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 3. HOOKE'S LAW & SPRINGS
    // ========================================================================
    case 'hooke': {
      const springK = Number(metrics.springK ?? phys.springK ?? 25.0);
      const mass = Number(metrics.mass ?? phys.mass ?? 1.0);
      const displacement = Number(metrics.maxDisplacement ?? Math.abs(phys.displacement || 0));
      const springForce = Number(metrics.peakForce ?? Math.abs(phys.springForce || computeSpringRestoringForce(springK, displacement)));
      const potEnergy = Number(metrics.peakPE ?? phys.potentialEnergy ?? computeSpringPotentialEnergy(springK, displacement));
      const kinEnergy = Number(metrics.peakKE ?? phys.kineticEnergy ?? 0);
      const periodTheo = computeSpringPeriod(mass, springK);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || displacement > 0.02 || potEnergy > 0.001)
      );

      apparatus = [
        { parameter: "Spring Stiffness (k)", value: springK.toFixed(1), unit: "Newtons / meter (N/m)", notes: "Elastic restoring constant" },
        { parameter: "Attached Bob Mass (m)", value: mass.toFixed(2), unit: "Kilograms (kg)", notes: "Harmonic oscillator mass" },
        { parameter: "Theoretical Period (T)", value: periodTheo.toFixed(2), unit: "Seconds (s)", notes: "T = 2π√(m/k)" },
        { parameter: "Center Equilibrium (x_0)", value: "0.00", unit: "Meters (m)", notes: "Resting zero datum" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Max Displacement (x)", value: displacement.toFixed(2), unit: "m", isMeasured: true },
          { label: "Peak Restoring Force (F)", value: springForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Elastic Potential Energy (U_s)", value: potEnergy.toFixed(3), unit: "J", isMeasured: true },
          { label: "Peak Kinetic Energy (KE)", value: kinEnergy.toFixed(3), unit: "J", isMeasured: true },
          { label: "Total Mechanical Energy", value: (potEnergy + kinEnergy).toFixed(3), unit: "J", isMeasured: true }
        ];

        const theoForce = springK * displacement;
        const diffForce = Math.abs(springForce - theoForce);
        const pctDev = theoForce > 0 ? ((diffForce / theoForce) * 100).toFixed(1) : "0.0";

        analysis = {
          governingEquation: "F_{spring} = -k \\cdot x, \\quad U_s = \\frac{1}{2} k x^2",
          isEmpiricallyVerified: displacement > 0.02,
          verificationStatus: displacement > 0.02 ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: `Verified Hooke's Law (F = -k·x). Displacing the spring mass by ${displacement.toFixed(2)} m generated an opposing restoring force of ${springForce.toFixed(2)} N.`,
          theoreticalComparison: `At displacement x = ${displacement.toFixed(2)} m with k = ${springK.toFixed(1)} N/m, theoretical restoring force is ${theoForce.toFixed(2)} N and theoretical elastic potential energy is ${potEnergy.toFixed(3)} J. Conservation of mechanical energy is observed throughout the oscillation.`,
          quantitativeComparison: [
            { metric: "Restoring Force", theoretical: `${theoForce.toFixed(2)} N`, observed: `${springForce.toFixed(2)} N`, deviation: `${pctDev}%` },
            { metric: "Theoretical Period", theoretical: `${periodTheo.toFixed(2)} s`, observed: `${periodTheo.toFixed(2)} s`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 4. COLLISIONS & MOMENTUM
    // ========================================================================
    case 'collision': {
      const fData = metrics.forensicData || phys.forensicData;
      const b1Mass = Number(metrics.b1Mass ?? phys.mass ?? 1.0);
      const b2Mass = Number(metrics.b2Mass ?? phys.mass2 ?? 1.0);
      const collisionOccurred = Boolean(metrics.collisionOccurred || phys.collisionOccurred || fData);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || collisionOccurred || (phys.pTotal && phys.pTotal > 0))
      );

      apparatus = [
        { parameter: "Striker Pod 1 Mass (m₁)", value: b1Mass.toFixed(2), unit: "Kilograms (kg)", notes: "Striker pod on air track" },
        { parameter: "Target Drone 2 Mass (m₂)", value: b2Mass.toFixed(2), unit: "Kilograms (kg)", notes: "Target drone on air track" },
        {
          parameter: "Restitution Regime",
          value: fData?.type === 'inelastic' || phys.collisionType === 'inelastic' ? "e = 0.0 (Perfect Inelastic)" : "e = 1.0 (Elastic)",
          unit: "Dimensionless",
          notes: "Coefficient of restitution"
        }
      ];

      if (hasEmpiricalData && fData) {
        const pBefore = Number(fData.p_total_before ?? fData.pBefore ?? (b1Mass * Number(fData.v1_before ?? 0) + b2Mass * Number(fData.v2_before ?? 0)));
        const pAfter = Number(fData.p_total_after ?? fData.pAfter ?? pBefore);
        const keBefore = Number(fData.ke_total_before ?? fData.keBefore ?? 0);
        const keAfter = Number(fData.ke_total_after ?? fData.keAfter ?? 0);
        const v1Before = Number(fData.v1_before ?? fData.v1i ?? 0);
        const v1After = Number(fData.v1_after ?? fData.v1f ?? 0);
        const v2Before = Number(fData.v2_before ?? fData.v2i ?? 0);
        const v2After = Number(fData.v2_after ?? fData.v2f ?? 0);

        measurements = [
          { label: "Initial System Momentum (p_i)", value: pBefore.toFixed(2), unit: "kg·m/s", isMeasured: true },
          { label: "Final System Momentum (p_f)", value: pAfter.toFixed(2), unit: "kg·m/s", isMeasured: true },
          { label: "Initial Kinetic Energy (KE_i)", value: keBefore.toFixed(2), unit: "J", isMeasured: true },
          { label: "Final Kinetic Energy (KE_f)", value: keAfter.toFixed(2), unit: "J", isMeasured: true },
          { label: "Pod 1 Velocity Transfer", value: `${v1Before.toFixed(2)} → ${v1After.toFixed(2)}`, unit: "m/s", isMeasured: true },
          { label: "Drone 2 Velocity Transfer", value: `${v2Before.toFixed(2)} → ${v2After.toFixed(2)}`, unit: "m/s", isMeasured: true }
        ];

        const momDiff = Math.abs(pBefore - pAfter);
        const isInelastic = fData.type === 'inelastic';

        analysis = {
          governingEquation: "p_{total,before} = p_{total,after} = m_1 v_{1} + m_2 v_{2}",
          isEmpiricallyVerified: true,
          verificationStatus: "VERIFIED",
          verificationSummary: `Verified Conservation of Linear Momentum [${isInelastic ? 'Inelastic e=0.0' : 'Elastic e=1.0'}]. Initial system momentum (${pBefore.toFixed(2)} kg·m/s) equals final momentum (${pAfter.toFixed(2)} kg·m/s) with 0.00% physical error.`,
          theoreticalComparison: isInelastic
            ? `In this inelastic collision, total momentum was conserved at ${pBefore.toFixed(2)} kg·m/s. Kinetic energy dissipated from ${keBefore.toFixed(2)} J to ${keAfter.toFixed(2)} J as the bodies coupled permanently.`
            : `In this elastic collision, total momentum (${pBefore.toFixed(2)} kg·m/s) and total kinetic energy (${keBefore.toFixed(2)} J) were both strictly conserved.`,
          quantitativeComparison: [
            { metric: "Total Momentum", theoretical: `${pBefore.toFixed(2)} kg·m/s`, observed: `${pAfter.toFixed(2)} kg·m/s`, deviation: `${(momDiff * 100).toFixed(2)}%` },
            { metric: "Total Kinetic Energy", theoretical: `${keBefore.toFixed(2)} J`, observed: `${keAfter.toFixed(2)} J`, deviation: isInelastic ? "Dissipated (e=0)" : "0.0%" }
          ]
        };
      } else if (hasEmpiricalData) {
        measurements = [
          { label: "Pod 1 Velocity (v₁)", value: Number(phys.v1 || 0).toFixed(2), unit: "m/s", isMeasured: true },
          { label: "Drone 2 Velocity (v₂)", value: Number(phys.v2 || 0).toFixed(2), unit: "m/s", isMeasured: true },
          { label: "System Momentum (p_tot)", value: Number(phys.pTotal || 0).toFixed(2), unit: "kg·m/s", isMeasured: true },
          { label: "System Kinetic Energy", value: Number(phys.keTotal || 0).toFixed(2), unit: "J", isMeasured: true }
        ];

        analysis = {
          governingEquation: "p_{total} = m_1 v_1 + m_2 v_2",
          isEmpiricallyVerified: true,
          verificationStatus: "VERIFIED",
          verificationSummary: "Carts active in pre-collision approach or motion. System linear momentum vector tracked continuously.",
          theoreticalComparison: `System momentum is monitored at ${Number(phys.pTotal || 0).toFixed(2)} kg·m/s across isolated low-friction air track.`,
          quantitativeComparison: null
        };
      }
      break;
    }

    // ========================================================================
    // 5. PROJECTILE MOTION
    // ========================================================================
    case 'projectile': {
      const angle = Number(metrics.angle ?? phys.projAngle ?? userConfig.projAngle ?? 45);
      const v0 = Number(metrics.v0 ?? phys.projV0 ?? userConfig.projV0 ?? 5.0);
      const range = Number(metrics.range ?? phys.range ?? 0);
      const maxHeight = Number(metrics.maxHeight ?? phys.maxHeight ?? 0);
      const flightTime = Number(metrics.flightTime ?? phys.flightTime ?? 0);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || range > 0 || flightTime > 0 || phys.isAirborne)
      );

      apparatus = [
        { parameter: "Launch Angle (θ)", value: angle.toFixed(0), unit: "Degrees (°)", notes: "Elevation angle above horizontal" },
        { parameter: "Initial Launch Velocity (v₀)", value: v0.toFixed(1), unit: "Meters / second (m/s)", notes: "Muzzle launch speed" },
        { parameter: "Gravitational Field (g)", value: GRAVITY_EARTH.toFixed(2), unit: "Meters / second² (m/s²)", notes: "Earth downward gravity" }
      ];

      if (hasEmpiricalData) {
        const rad = (angle * Math.PI) / 180;
        const v0x = v0 * Math.cos(rad);
        const v0y = v0 * Math.sin(rad);

        measurements = [
          { label: "Horizontal Range (R)", value: range.toFixed(2), unit: "m", isMeasured: true },
          { label: "Apex Height (H_max)", value: maxHeight.toFixed(2), unit: "m", isMeasured: true },
          { label: "Total Flight Time (t)", value: flightTime.toFixed(2), unit: "s", isMeasured: true },
          { label: "Initial Horizontal Velocity (v₀x)", value: v0x.toFixed(2), unit: "m/s", isMeasured: true },
          { label: "Initial Vertical Velocity (v₀y)", value: v0y.toFixed(2), unit: "m/s", isMeasured: true }
        ];

        const theo = computeProjectileTheoretical(v0, angle, GRAVITY_EARTH);
        const devR = theo.range > 0 ? ((Math.abs(range - theo.range) / theo.range) * 100).toFixed(1) : "0.0";
        const devH = theo.maxHeight > 0 ? ((Math.abs(maxHeight - theo.maxHeight) / theo.maxHeight) * 100).toFixed(1) : "0.0";

        analysis = {
          governingEquation: "R = \\frac{v_0^2 \\sin(2\\theta)}{g}, \\quad H_{max} = \\frac{v_0^2 \\sin^2(\\theta)}{2g}",
          isEmpiricallyVerified: range > 0 || flightTime > 0,
          verificationStatus: (range > 0 || flightTime > 0) ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: `Verified 2D Kinematics and Parabolic Trajectory. Horizontal motion (a_x = 0) and vertical acceleration (a_y = -9.80 m/s²) operated independently throughout flight.`,
          theoreticalComparison: `At launch angle θ = ${angle}° and launch speed v₀ = ${v0.toFixed(1)} m/s, theoretical range is R = ${theo.range.toFixed(2)} m and apex height is H = ${theo.maxHeight.toFixed(2)} m. Observed range was ${range.toFixed(2)} m.`,
          quantitativeComparison: [
            { metric: "Horizontal Range", theoretical: `${theo.range.toFixed(2)} m`, observed: `${range.toFixed(2)} m`, deviation: `${devR}%` },
            { metric: "Apex Height", theoretical: `${theo.maxHeight.toFixed(2)} m`, observed: `${maxHeight.toFixed(2)} m`, deviation: `${devH}%` }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 6. SIMPLE PENDULUM
    // ========================================================================
    case 'pendulum': {
      const length = Number(metrics.length ?? phys.pendulumLength ?? userConfig.pendulumLength ?? 1.5);
      const mass = Number(metrics.mass ?? phys.pendulumMass ?? userConfig.pendulumMass ?? 0.8);
      const thetaDeg = Number(metrics.maxThetaDeg ?? Math.abs(phys.thetaDeg || 0));
      const peakOmega = Number(metrics.peakOmega ?? Math.abs(phys.pendulumOmega || 0));
      const potEnergy = Number(metrics.peakPE ?? phys.potentialEnergy ?? 0);
      const kinEnergy = Number(metrics.peakKE ?? phys.kineticEnergy ?? 0);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || thetaDeg > 0.5 || peakOmega > 0.02)
      );

      const theoPeriodSmall = computePendulumSmallAnglePeriod(length, GRAVITY_EARTH);
      const thetaRad = (thetaDeg * Math.PI) / 180;
      const theoPeriodLarge = computePendulumLargeAnglePeriod(length, thetaRad, GRAVITY_EARTH);

      apparatus = [
        { parameter: "Suspension Cord Length (L)", value: length.toFixed(2), unit: "Meters (m)", notes: "Pivot to center-of-mass" },
        { parameter: "Bob Inertial Mass (m)", value: mass.toFixed(2), unit: "Kilograms (kg)", notes: "Suspended pendulum bob" },
        { parameter: "Small-Angle Period (T₀)", value: theoPeriodSmall.toFixed(2), unit: "Seconds (s)", notes: "T₀ = 2π√(L/g)" },
        { parameter: "Gravitational Field (g)", value: GRAVITY_EARTH.toFixed(2), unit: "Meters / second² (m/s²)", notes: "Earth downward gravity" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Release Angle (θ)", value: thetaDeg.toFixed(1), unit: "°", isMeasured: true },
          { label: "Peak Angular Velocity (ω)", value: peakOmega.toFixed(2), unit: "rad/s", isMeasured: true },
          { label: "Maximum Potential Energy (U)", value: potEnergy.toFixed(2), unit: "J", isMeasured: true },
          { label: "Peak Kinetic Energy (K)", value: kinEnergy.toFixed(2), unit: "J", isMeasured: true },
          { label: "Finite-Angle Corrected Period (T)", value: theoPeriodLarge.toFixed(2), unit: "s", isMeasured: true }
        ];

        analysis = {
          governingEquation: "T \\approx 2\\pi \\sqrt{\\frac{L}{g}} \\left(1 + \\frac{1}{16}\\theta_0^2\\right)",
          isEmpiricallyVerified: thetaDeg > 0.5,
          verificationStatus: thetaDeg > 0.5 ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: `Verified Simple Harmonic Motion for pendulum oscillation. Restoring torque τ = -m·g·L·sin(θ) produced periodic oscillation with small-angle period T = ${theoPeriodSmall.toFixed(2)} s.`,
          theoreticalComparison: `At amplitude θ = ${thetaDeg.toFixed(1)}°, the small-angle period is ${theoPeriodSmall.toFixed(2)} s, while finite-angle correction yields ${theoPeriodLarge.toFixed(2)} s. Mechanical energy converted between potential energy (${potEnergy.toFixed(2)} J) and kinetic energy (${kinEnergy.toFixed(2)} J).`,
          quantitativeComparison: [
            { metric: "Small-Angle Period", theoretical: `${theoPeriodSmall.toFixed(2)} s`, observed: `${theoPeriodSmall.toFixed(2)} s`, deviation: "0.0%" },
            { metric: "Large-Angle Corrected Period", theoretical: `${theoPeriodLarge.toFixed(2)} s`, observed: `${theoPeriodLarge.toFixed(2)} s`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 7. ELECTRIC FIELD & CHARGES
    // ========================================================================
    case 'electric': {
      const q1 = Number(metrics.q1 ?? phys.charge1Q ?? 2.0);
      const q2 = Number(metrics.q2 ?? phys.charge2Q ?? -2.0);
      const probeQ = Number(metrics.probeQ ?? phys.chargeTestQ ?? 1.0);
      const probeX = Number(metrics.probeX ?? phys.posX ?? 0.0);
      const probeY = Number(metrics.probeY ?? phys.posY ?? 0.35);
      const fieldMag = Number(metrics.fieldMag ?? phys.electricFieldMag ?? 0);
      const potential = Number(metrics.potential ?? phys.electricPotential ?? 0);
      const probeForce = Number(metrics.force ?? phys.force ?? computeElectrostaticForce(probeQ, fieldMag));

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || fieldMag > 0 || phys.electricFieldMag !== undefined)
      );

      apparatus = [
        { parameter: "Source Charge 1 (q₁)", value: q1.toFixed(1), unit: "Microcoulombs (μC)", notes: "Located at (-0.45, 0.00) m" },
        { parameter: "Source Charge 2 (q₂)", value: q2.toFixed(1), unit: "Microcoulombs (μC)", notes: "Located at (+0.45, 0.00) m" },
        { parameter: "Test Probe Charge (q₀)", value: probeQ.toFixed(1), unit: "Microcoulombs (μC)", notes: "Mobile measurement sensor" },
        { parameter: "Coulomb Constant (k_e)", value: "8.99 × 10⁹", unit: "N·m²/C²", notes: "Electrostatic permittivity factor" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Electric Field Magnitude (|E|)", value: fieldMag.toFixed(2), unit: "N/C", isMeasured: true },
          { label: "Electric Potential (V)", value: potential.toFixed(1), unit: "V", isMeasured: true },
          { label: "Force on Test Probe (|F|)", value: probeForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Probe Position Coordinates", value: `(${probeX.toFixed(2)}, ${probeY.toFixed(2)})`, unit: "m", isMeasured: true }
        ];

        analysis = {
          governingEquation: "\\vec{E} = k_e \\sum \\frac{q_i}{r_i^2} \\hat{r}_i, \\quad \\vec{F} = q_0 \\vec{E}",
          isEmpiricallyVerified: fieldMag > 0,
          verificationStatus: fieldMag > 0 ? "VERIFIED" : "INCONCLUSIVE",
          verificationSummary: `Verified Coulomb's Law and Vector Superposition. The net electric field vector at (${probeX.toFixed(2)}, ${probeY.toFixed(2)}) m equals the vector sum of fields from charges q₁ and q₂.`,
          theoreticalComparison: `At probe position (${probeX.toFixed(2)}, ${probeY.toFixed(2)}) m, resultant field strength is |E| = ${fieldMag.toFixed(2)} N/C with electric potential V = ${potential.toFixed(1)} V. Electrostatic force on probe q₀ = ${probeQ.toFixed(1)} μC is F = ${probeForce.toFixed(2)} N.`,
          quantitativeComparison: [
            { metric: "Electric Field (|E|)", theoretical: `${fieldMag.toFixed(2)} N/C`, observed: `${fieldMag.toFixed(2)} N/C`, deviation: "0.0%" },
            { metric: "Electric Potential (V)", theoretical: `${potential.toFixed(1)} V`, observed: `${potential.toFixed(1)} V`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 8. WAVE INTERFERENCE
    // ========================================================================
    case 'wave': {
      const a1 = Number(metrics.a1 ?? phys.waveA1 ?? 1.0);
      const a2 = Number(metrics.a2 ?? phys.waveA2 ?? 1.0);
      const freq = Number(metrics.freq ?? phys.waveFreq ?? 1.0);
      const phaseDeg = Number(metrics.phaseDeg ?? phys.wavePhaseDeg ?? 0);
      const phaseRad = (phaseDeg * Math.PI) / 180;
      const resAmp = Number(metrics.resultantAmp ?? phys.waveResultantAmp ?? computeInterferenceResultant(a1, a2, phaseRad)?.resultantAmp ?? 0);
      const regime = (metrics.regime || phys.waveRegime || (Math.abs(phaseDeg - 180) < 15 ? 'destructive' : (phaseDeg < 15 || phaseDeg > 345) ? 'constructive' : 'partial')).toUpperCase();

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || a1 > 0 || a2 > 0)
      );

      apparatus = [
        { parameter: "Wave 1 Amplitude (A₁)", value: a1.toFixed(2), unit: "Meters (m)", notes: "Primary coherent harmonic wave" },
        { parameter: "Wave 2 Amplitude (A₂)", value: a2.toFixed(2), unit: "Meters (m)", notes: "Secondary coherent harmonic wave" },
        { parameter: "Phase Shift (Δφ)", value: phaseDeg.toFixed(0), unit: "Degrees (°)", notes: "Relative spatial phase displacement" },
        { parameter: "Oscillation Frequency (f)", value: freq.toFixed(1), unit: "Hertz (Hz)", notes: "Source frequency" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Resultant Amplitude (A_res)", value: resAmp.toFixed(2), unit: "m", isMeasured: true },
          { label: "Interference Regime", value: regime, unit: "", isMeasured: true },
          { label: "Phase Shift (Δφ)", value: `${phaseDeg.toFixed(0)}°`, unit: "", isMeasured: true },
          { label: "Constructive Limit (A₁ + A₂)", value: (a1 + a2).toFixed(2), unit: "m", isMeasured: true },
          { label: "Destructive Limit (|A₁ - A₂|)", value: Math.abs(a1 - a2).toFixed(2), unit: "m", isMeasured: true }
        ];

        const theoResObj = computeInterferenceResultant(a1, a2, phaseRad);
        const theoAmp = typeof theoResObj === 'object' && theoResObj !== null ? Number(theoResObj.resultantAmp ?? 0) : Number(theoResObj ?? 0);

        analysis = {
          governingEquation: "A_{res} = \\sqrt{A_1^2 + A_2^2 + 2 A_1 A_2 \\cos(\\Delta\\phi)}",
          isEmpiricallyVerified: true,
          verificationStatus: "VERIFIED",
          verificationSummary: `Verified Principle of Wave Superposition. Harmonic waves overlapping with phase shift Δφ = ${phaseDeg}° produced resultant amplitude A_res = ${resAmp.toFixed(2)} m in the ${regime} regime.`,
          theoreticalComparison: `Superposition theory predicts A_res = ${theoAmp.toFixed(2)} m. Constructive peak limit is ${(a1 + a2).toFixed(2)} m and destructive minimum is ${Math.abs(a1 - a2).toFixed(2)} m. Wave crests and troughs superpose linearly.`,
          quantitativeComparison: [
            { metric: "Resultant Amplitude", theoretical: `${theoAmp.toFixed(2)} m`, observed: `${resAmp.toFixed(2)} m`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 9. REFLECTION & REFRACTION
    // ========================================================================
    case 'optics': {
      const incAngle = Number(metrics.incidentAngleDeg ?? phys.opticsIncidentAngle ?? 45);
      const n1 = Number(metrics.n1 ?? phys.opticsN1 ?? 1.0);
      const n2 = Number(metrics.n2 ?? phys.opticsN2 ?? 1.5);
      const rays = computeOpticsRays({ incidentAngleDeg: incAngle, n1, n2 });

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || incAngle > 0)
      );

      apparatus = [
        { parameter: "Angle of Incidence (θ₁)", value: incAngle.toFixed(1), unit: "Degrees (°)", notes: "Relative to surface normal" },
        { parameter: "Medium 1 Refractive Index (n₁)", value: n1.toFixed(2), unit: "Dimensionless", notes: n1 === 1.0 ? "Air (n=1.00)" : "Denser Medium" },
        { parameter: "Medium 2 Refractive Index (n₂)", value: n2.toFixed(2), unit: "Dimensionless", notes: n2 === 1.5 ? "Crown Glass (n=1.50)" : "Rarer Medium" },
        { parameter: "Critical Angle (θ_c)", value: rays.criticalAngleDeg ? `${rays.criticalAngleDeg.toFixed(1)}°` : "N/A (n₁ ≤ n₂)", unit: "", notes: "Threshold for TIR" }
      ];

      if (hasEmpiricalData) {
        measurements = [
          { label: "Angle of Reflection (θ_r)", value: `${incAngle.toFixed(1)}°`, unit: "", isMeasured: true },
          { label: "Angle of Refraction (θ₂)", value: rays.isTotalInternalReflection ? "TIR (No Ray)" : `${rays.refractionAngleDeg?.toFixed(1)}°`, unit: "", isMeasured: true },
          { label: "Optical Regime", value: rays.isTotalInternalReflection ? "TOTAL INTERNAL REFLECTION" : "STANDARD SNELL'S REFRACTION", unit: "", isMeasured: true },
          { label: "Refractive Index Ratio (n₂/n₁)", value: (n2 / n1).toFixed(2), unit: "Dimensionless", isMeasured: true }
        ];

        analysis = {
          governingEquation: "n_1 \\sin(\\theta_1) = n_2 \\sin(\\theta_2), \\quad \\theta_r = \\theta_1",
          isEmpiricallyVerified: true,
          verificationStatus: "VERIFIED",
          verificationSummary: rays.isTotalInternalReflection
            ? `Verified Total Internal Reflection! Incident angle θ₁ = ${incAngle.toFixed(1)}° exceeded critical angle θ_c = ${rays.criticalAngleDeg?.toFixed(1)}°. 100% of incident optical energy is reflected.`
            : `Verified Snell's Law and Law of Reflection. Reflected angle θ_r = ${incAngle.toFixed(1)}° and refracted angle θ₂ = ${rays.refractionAngleDeg?.toFixed(1)}° conform precisely to boundary electromagnetic conditions.`,
          theoreticalComparison: rays.isTotalInternalReflection
            ? `Light travelling from dense medium (n₁ = ${n1.toFixed(2)}) to rarer medium (n₂ = ${n2.toFixed(2)}) cannot transmit beyond critical angle θ_c = arcsin(n₂/n₁) = ${rays.criticalAngleDeg?.toFixed(1)}°.`
            : `Snell's Law: n₁·sin(θ₁) = ${(n1 * Math.sin(incAngle * Math.PI / 180)).toFixed(4)}, matching n₂·sin(θ₂) = ${(n2 * Math.sin((rays.refractionAngleDeg || 0) * Math.PI / 180)).toFixed(4)}.`,
          quantitativeComparison: [
            { metric: "Reflection Angle (θ_r)", theoretical: `${incAngle.toFixed(1)}°`, observed: `${incAngle.toFixed(1)}°`, deviation: "0.0%" },
            { metric: "Refraction Angle (θ₂)", theoretical: rays.isTotalInternalReflection ? "TIR" : `${rays.refractionAngleDeg?.toFixed(1)}°`, observed: rays.isTotalInternalReflection ? "TIR" : `${rays.refractionAngleDeg?.toFixed(1)}°`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    // ========================================================================
    // 10. FRICTION & INCLINED PLANE
    // ========================================================================
    case 'incline': {
      const angleDeg = Number(metrics.angleDeg ?? phys.inclineAngle ?? 25);
      const mass = Number(metrics.mass ?? phys.inclineMass ?? 1.0);
      const muStatic = Number(metrics.muStatic ?? phys.inclineMuStatic ?? 0.45);
      const muKinetic = Number(metrics.muKinetic ?? phys.inclineMuKinetic ?? 0.30);
      const incPhys = computeInclinedPlanePhysics(mass, angleDeg, muStatic, muKinetic, GRAVITY_EARTH);

      hasEmpiricalData = Boolean(
        explicitHasMeasurements !== undefined
          ? explicitHasMeasurements
          : (metrics.hasInteracted || angleDeg > 0)
      );

      apparatus = [
        { parameter: "Incline Slope Angle (θ)", value: angleDeg.toFixed(1), unit: "Degrees (°)", notes: "Elevation above horizontal" },
        { parameter: "Block Inertial Mass (m)", value: mass.toFixed(2), unit: "Kilograms (kg)", notes: "Incline sliding payload" },
        { parameter: "Static Friction Coeff (μ_s)", value: muStatic.toFixed(2), unit: "Dimensionless", notes: "Breakaway threshold" },
        { parameter: "Kinetic Friction Coeff (μ_k)", value: muKinetic.toFixed(2), unit: "Dimensionless", notes: "Sliding resistance factor" },
        { parameter: "Angle of Repose (θ_c = arctan μ_s)", value: Number(incPhys.criticalAngleDeg || 0).toFixed(1), unit: "Degrees (°)", notes: "Critical slipping angle" }
      ];

      if (hasEmpiricalData) {
        const normForce = Number(incPhys.F_normal ?? incPhys.normalForce ?? 0);
        const parallelGrav = Number(incPhys.F_parallel ?? incPhys.parallelGravityForce ?? 0);
        const fricForce = Number(incPhys.frictionForce ?? 0);
        const accel = Number(incPhys.acceleration ?? 0);
        const isSliding = Boolean(incPhys.isSlipping);
        const critAngle = Number(incPhys.criticalAngleDeg ?? 0);
        const maxStaticFric = Number(incPhys.maxStaticFriction ?? 0);

        measurements = [
          { label: "Normal Force (N = mg cos θ)", value: normForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Parallel Gravity Force (mg sin θ)", value: parallelGrav.toFixed(2), unit: "N", isMeasured: true },
          { label: "Actual Friction Force (f)", value: fricForce.toFixed(2), unit: "N", isMeasured: true },
          { label: "Downhill Acceleration (a)", value: accel.toFixed(2), unit: "m/s²", isMeasured: true },
          { label: "Motion State", value: isSliding ? "SLIDING MOTION" : "STATIC EQUILIBRIUM", unit: "", isMeasured: true }
        ];

        analysis = {
          governingEquation: "a = g(\\sin\\theta - \\mu_k \\cos\\theta) \\quad (\\text{if } \\tan\\theta > \\mu_s)",
          isEmpiricallyVerified: true,
          verificationStatus: "VERIFIED",
          verificationSummary: isSliding
            ? `Verified Sliding Mechanics. Incline angle (${angleDeg.toFixed(1)}°) exceeds angle of repose (${critAngle.toFixed(1)}°). Net downhill acceleration is ${accel.toFixed(2)} m/s².`
            : `Verified Static Equilibrium. Incline angle (${angleDeg.toFixed(1)}°) is below angle of repose (${critAngle.toFixed(1)}°). Static friction (f_s = ${fricForce.toFixed(2)} N) balances downhill gravity.`,
          theoreticalComparison: `Normal force N = mg·cos(θ) = ${normForce.toFixed(2)} N dictates maximum static friction f_s,max = ${maxStaticFric.toFixed(2)} N. Downhill gravitational pull is ${parallelGrav.toFixed(2)} N.`,
          quantitativeComparison: [
            { metric: "Normal Force (N)", theoretical: `${normForce.toFixed(2)} N`, observed: `${normForce.toFixed(2)} N`, deviation: "0.0%" },
            { metric: "Friction Force (f)", theoretical: `${fricForce.toFixed(2)} N`, observed: `${fricForce.toFixed(2)} N`, deviation: "0.0%" },
            { metric: "Acceleration (a)", theoretical: `${accel.toFixed(2)} m/s²`, observed: `${accel.toFixed(2)} m/s²`, deviation: "0.0%" }
          ]
        };
      }
      break;
    }

    default: {
      hasEmpiricalData = Boolean(explicitHasMeasurements || metrics.hasInteracted);
      apparatus = [
        { parameter: "Configured Parameter", value: "1.00", unit: "SI Units", notes: "Laboratory Module Setting" }
      ];
      measurements = [];
      break;
    }
  }

  // Handle unperformed / missing data
  if (!hasEmpiricalData) {
    analysis.isEmpiricallyVerified = false;
    analysis.verificationStatus = "AWAITING_DATA";
    analysis.verificationSummary = `Awaiting empirical simulation telemetry. Empirical verification of ${expDef.primaryFormula} requires interacting with the virtual 3D simulation.`;
    analysis.theoreticalComparison = `Theoretical law predicts behavior governed by ${expDef.primaryFormula}. Run the simulation to compare observed vector measurements against theoretical values.`;
    analysis.quantitativeComparison = null;
  }

  // Determine certification badge
  let badgeTitle = 'UNPERFORMED SESSION';
  let badgeSub = 'AWAITING SIMULATION DATA';
  let badgeType = 'unperformed';

  if (hasEmpiricalData && rawScore !== null) {
    badgeTitle = isMastered ? 'LAB VERIFIED & MASTERED' : 'EVALUATED (REVIEW RECOMMENDED)';
    badgeSub = `SCORE: ${rawScore}%`;
    badgeType = isMastered ? 'verified' : 'evaluated';
  } else if (hasEmpiricalData && rawScore === null) {
    badgeTitle = 'DATA LOGGED • QUIZ PENDING';
    badgeSub = 'TAKE QUIZ TO VERIFY';
    badgeType = 'pending_quiz';
  } else if (!hasEmpiricalData && rawScore !== null) {
    badgeTitle = 'QUIZ RECORDED • SIM PENDING';
    badgeSub = `SCORE: ${rawScore}% (MEASUREMENTS MISSING)`;
    badgeType = 'awaiting_sim';
  }

  // Mastery assessment section
  const mastery = {
    score: rawScore,
    isMastered,
    statusText: rawScore === null ? 'AWAITING QUIZ' : isMastered ? 'MASTERED' : 'NEEDS REVIEW',
    concepts: expDef.concepts || [],
    competencyNotes:
      rawScore === null
        ? 'Student has not completed the concept mastery quiz for this laboratory. Take the quiz from the lab workspace to record verified scores.'
        : isMastered
          ? 'Student demonstrated thorough comprehension of underlying physical relationships, dimensional analysis, and vector mechanics.'
          : 'Review the formulas and live HUD graphs in the lab to reinforce relationships between parameters, vector forces, and conservation laws.'
  };

  return {
    id: `rep_${id}_${Date.now()}`,
    timestamp,
    investigator: studentName || 'Student Physicist',
    experimentId: id,
    experimentTitle: expDef.title,
    title: expDef.title,
    topic: expDef.topic,
    objective: expDef.objective,
    hypothesis: getExperimentHypothesis(id, expDef),
    primaryFormula: expDef.primaryFormula,
    secondaryFormula: expDef.secondaryFormula,
    assumptions: expDef.assumptions,
    prerequisites: expDef.prerequisites,
    hasMeasurements: hasEmpiricalData,
    missingDataReason: hasEmpiricalData ? null : "No active physical interaction or telemetry recorded for this laboratory module yet.",
    howToMeasure: hasEmpiricalData ? null : getHowToMeasureGuide(id),
    apparatus,
    measurements,
    analysis,
    mastery,
    badge: {
      title: badgeTitle,
      subtitle: badgeSub,
      type: badgeType
    }
  };
}
